import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { withGlassBridgeTimeout } from './native-glass-lab.js'

const file = name => readFileSync(new URL(name, import.meta.url), 'utf8')
const swift = name => readFileSync(new URL('../../ios/App/App/' + name, import.meta.url), 'utf8')

describe('iOS 27 native Liquid Glass Phase 0 compositor', () => {
  it('settles successful WebKit replies without waiting for fallback', async () => {
    await expect(withGlassBridgeTimeout(Promise.resolve({ supported: true }), 'UIKit test', 300))
      .resolves.toEqual({ supported: true })
  })

  it('reports a missing native response within a bounded time', async () => {
    await expect(withGlassBridgeTimeout(new Promise(() => {}), 'UIKit inspect', 15))
      .rejects.toThrow('UIKit inspect timed out')
  })
  it('uses real UIKit glass materials, never a CSS-only fake', () => {
    const overlay = swift('NativeGlassLabOverlay.swift')
    expect(overlay).toContain('@available(iOS 26.0, *)')
    expect(overlay).toContain('UIGlassContainerEffect()')
    expect(overlay).toContain('glassContainer = UIVisualEffectView(effect: combined)')
    expect(overlay).toContain('UIButton.Configuration.prominentGlass()')
    expect(overlay).toContain('dockSurface = UIVisualEffectView(effect: dockGlass)')
    expect(overlay).toContain('dockGlass.isInteractive = true')
    expect(overlay).toContain('glassContainer.contentView.addSubview(dockSurface)')
    expect(overlay).toContain('dockSurface.contentView.addSubview(row)')
    // One continuous glass capsule and one prominent Start, NOT five bubbles.
    expect(overlay).not.toContain('UIButton.Configuration.glass()')
    expect(overlay).toContain('row.spacing = 0')
    expect(overlay).toContain('startButton.widthAnchor.constraint(equalToConstant: 56)')
    expect(overlay).toContain('caption.numberOfLines = 1')
    expect(overlay).toContain('caption.adjustsFontSizeToFitWidth = true')
    expect(overlay).toContain('button.accessibilityTraits.insert(.selected)')
    expect(overlay).toContain('caption.font = .systemFont(ofSize: 11, weight: .semibold)')
    expect(overlay).toContain('icon.tintColor = .label')
    expect(overlay).toContain('caption.textColor = .label')
    expect(overlay).toContain('tabPressPlates: [String: UIView]')
    expect(overlay).toContain('pressPlate.isUserInteractionEnabled = false')
    expect(overlay).toContain('UIColor.label.withAlphaComponent(0.18)')
    expect(overlay).toContain('button.transform = pressed')
    expect(overlay).toContain('private func setTabPressed(')
    expect(overlay).toContain('private func setStartPressed(')
    expect(overlay).toContain('for: [.touchDown, .touchDragEnter]')
    expect(overlay).toContain('for: [.touchDragExit, .touchCancel, .touchUpOutside]')
    expect(overlay).toContain('UIView.animate(withDuration: 0.24')
    expect(overlay).toContain('traitCollectionDidChange')
    expect(overlay).toContain('UIAccessibility.isReduceMotionEnabled')
    expect(overlay).toContain('UISelectionFeedbackGenerator().selectionChanged()')
    expect(overlay).toContain('button.accessibilityIdentifier = "glass-lab-" + key')
  })

  it('keeps the fullscreen overlay transparent with touch pass-through', () => {
    const overlay = swift('NativeGlassLabOverlay.swift')
    expect(overlay).toContain('backgroundColor = .clear')
    expect(overlay).toContain('isOpaque = false')
    expect(overlay).toContain('override func point(inside point: CGPoint, with event: UIEvent?) -> Bool')
    expect(overlay).toContain('button.convert(button.bounds, to: self).contains(point)')
  })

  it('exposes a gated Capacitor 7 bridge with a reversible lifecycle', () => {
    const plug = swift('NativeGlassLabPlugin.swift')
    const host = swift('AppBridgeViewController.swift')
    expect(plug).toContain('CAPPlugin, CAPBridgedPlugin')
    expect(plug).toContain('public let jsName = "NativeGlassLab"')
    for (const method of ['inspect', 'show', 'hide']) {
      expect(plug).toContain('CAPPluginMethod(name: "' + method + '"')
    }
    expect(plug).toContain('if #available(iOS 26.0, *)')
    expect(host).toContain('bridge?.registerPluginInstance(glassLab)')
    expect(host).toContain('view.addSubview(overlay)')
    expect(host).toContain('view.bringSubviewToFront(overlay)')
    expect(host).toContain('hideGlassLab()')
    expect(host).toContain('WKScriptMessageHandlerWithReply')
    expect(host).toContain('contentWorld: .page, name: "openGymGlassLab"')
    expect(host).toContain('replyHandler(')
    expect(host).toContain('NativeGlassLabMessageHandler(host: self)')
    expect(host).toContain('view.addSubview(overlay)')
    expect(host).toContain("openGymGlassSelection")
    const pbx = readFileSync(new URL('../../ios/App/App.xcodeproj/project.pbxproj', import.meta.url), 'utf8')
    expect(pbx).toContain('NativeGlassLabOverlay.swift in Sources')
    expect(pbx).toContain('NativeGlassLabPlugin.swift in Sources')
  })

  it('never allows the proof to create duplicate production tab bars', () => {
    const app = file('../App.jsx')
    const lab = file('../views/GlassLab.jsx')
    const home = file('../views/Home.jsx')
    const js = file('./native-glass-lab.js')
    expect(app).toContain("loc.pathname === '/glass-lab'")
    expect(app).toContain('<Route path="/glass-lab" element={<GlassLab />} />')
    expect(lab).toContain('closeNativeGlassLab().catch(() => {})')
    expect(lab).toContain('listenNativeGlassLab(event =>')
    expect(js).toContain("Capacitor.getPlatform() === 'ios'")
    expect(js).toContain("Capacitor.isPluginAvailable('NativeGlassLab')")
    expect(home).toContain('<NativeGlassLabEntry />')
  })

  it('does not change the HealthKit or legacy HTML tabbar integration', () => {
    const app = file('../App.jsx')
    expect(app).toContain('<TabBar onStart={startFlow} />')
    const entry = file('../components/NativeGlassLabEntry.jsx')
    // The previous build hid the entire test entry if plugin inspection failed,
    // making a valid new IPA appear identical to the old user interface.
    expect(entry).toContain('if (!ios) return null')
    expect(entry).not.toContain('if (!available) return null')
    expect(entry).toContain('NATIVE_GLASS_STAGE')
    expect(entry).toContain('Native bridge unavailable')
    expect(entry).toContain("navigate('/glass-lab')")
    const js = file('./native-glass-lab.js')
    expect(js).toContain('Stage 0 R5')
    expect(js).toContain('all-native-bridges-unavailable')
    expect(js).toContain("webkitMessage('inspect')")
    expect(js).toContain('withGlassBridgeTimeout')
    expect(js).toContain('WebKit: reply handler absent')
    expect(js).toContain("window.addEventListener('openGymGlassSelection', listener)")
    const lab = file('../views/GlassLab.jsx')
    expect(lab).toContain('WebKit reply handler:')
    expect(lab).toContain('Bridge transport:')
    expect(lab).toContain('Bridge registration:')
    expect(lab).toContain('Native error:')
    expect(lab).toContain('Build marker:')
  })
})
